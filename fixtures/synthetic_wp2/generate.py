#!/usr/bin/env python3
"""Generate the SYNTHETIC WP2 fixture suite (DECISIONS.md D-050).

Every fixture is a small labeled synthetic structural/statistical design: a declaration
(`declaration_synthetic.yaml`) and a data table (`data_synthetic.csv`). The values are
built from fixed, exactly representable patterns, not drawn at random and not simulated
from any physical process. They demonstrate software behavior only. They are not fab
data and make no claim about any real process.

This file builds inputs only. It contains no expected decision. The preregistered
expectations are recorded separately in `expectations.json`, which this generator never
reads or writes.

Response construction (all exact decimals):
    y = base + treatment effect + unit deviation + wafer deviation + site deviation
  - unit deviations within each treatment level: centered pattern, e.g. r = 4 gives
    (-1.5, -0.5, 0.5, 1.5), the same in every level unless a fixture says otherwise;
  - wafer deviations within a unit: centered, step 0.25; site deviations within a
    wafer: centered, step 0.1. Both sum to zero within their parent.

Usage (needs PyYAML, so run with the project .venv):
    .venv/bin/python fixtures/synthetic_wp2/generate.py          # write all fixtures
    .venv/bin/python fixtures/synthetic_wp2/generate.py --check  # verify files match
"""
