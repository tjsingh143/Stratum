def unit_dev_cells(block_of_rep, block_effect):
    """Unit deviation = block effect + (-0.5, +0.5) alternating within each cell."""
    def f(i, rep):
        return block_effect[block_of_rep(i, rep)] + (Q(-1, 2) if rep % 2 == 0 else Q(1, 2))
    return f


