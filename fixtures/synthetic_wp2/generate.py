LABEL = "SYNTHETIC structural/statistical fixture. Not physical data and not fab data."
UNITS = "a.u. (synthetic)"
ASSIGN = {"method": "systematic",
          "description": "Synthetic fixture: levels are assigned by construction."}


def centered(n, step):
    """n values symmetric about zero with spacing `step` (sum exactly zero)."""
    return [Q(2 * i - (n - 1), 2) * step for i in range(n)]


def fmt(value):
    """Exact decimal text of a Fraction whose denominator divides a power of ten."""
    if not isinstance(value, Q):
        return str(value)           # already text (e.g. "NA", "bad", "")
    for k in range(7):
        v = value * 10 ** k
        if v.denominator == 1:
            n = v.numerator
            sign, digits = ("-" if n < 0 else ""), str(abs(n)).rjust(k + 1, "0")
            return sign + (digits[:-k] + "." + digits[-k:] if k else digits)
    raise ValueError("not a terminating decimal: %r" % value)


class Fixture:
    def __init__(self, fid, purpose, declaration, columns, rows):
        self.id, self.purpose = fid, purpose
        declaration["description"] = "SYNTHETIC FIXTURE %s: %s" % (fid, purpose)
        self.declaration, self.columns, self.rows = declaration, columns, rows

    def decl_text(self):
        head = ("# %s\n# Fixture %s. Generated by fixtures/synthetic_wp2/generate.py; do not "
                "edit by hand.\n" % (LABEL, self.id))
        body = yaml.safe_dump(self.declaration, sort_keys=False, allow_unicode=True,
                              default_flow_style=False, width=88)
        return head + body

    def data_text(self):
        buf = io.StringIO()
        w = csv.writer(buf, lineterminator="\n")
        w.writerow(self.columns)
        for row in self.rows:
            w.writerow([fmt(row[c]) if c in row else "" for c in self.columns])
        return buf.getvalue()


# ---------------------------------------------------------------------------
# T2: treatment `temp` applied to runs (or to wafers in the two-level form)
# ---------------------------------------------------------------------------
LV2 = ("low", "high")
LV3 = ("low", "mid", "high")
EFFECT = {"low": Q(0), "mid": Q(2), "high": Q(4)}


def t2_decl(levels=LV2, r=4, w=2, s=3, *, top_count=None, r_declared=None, wafer=None,
            site=None, nuisance=(), two_level=False):
    if two_level:
        hierarchy = [{"name": "wafer", "id_column": "wafer",
                      "count": top_count or len(levels) * r},
                     dict({"name": "site", "id_column": "site", "nested_in": "wafer",
                           "count_per_parent": s}, **(site or {}))]
        unit = "wafer"
    else:
        hierarchy = [{"name": "run", "id_column": "run", "count": top_count or len(levels) * r},
                     dict({"name": "wafer", "id_column": "wafer", "nested_in": "run",
                           "count_per_parent": w}, **(wafer or {})),
                     dict({"name": "site", "id_column": "site", "nested_in": "wafer",
                           "count_per_parent": s}, **(site or {}))]
        unit = "run"
    if len(levels) == 2:
        comparisons = [{"id": "high_vs_low", "kind": "pairwise", "factors": ["temp"],
                        "levels": ["high", "low"]}]
    else:
        comparisons = [{"id": "temp_overall", "kind": "overall", "factors": ["temp"]}]
    return {"stratum_declaration": 1, "claimed_template": "T2",
            "response": {"column": "y", "units": UNITS},
            "hierarchy": hierarchy,
            "treatments": [{"name": "temp", "column": "temp", "levels": list(levels),
                            "applied_to": unit,
                            "replicates_per_level": r_declared or r, "assignment": dict(ASSIGN)}],
            "nuisance_factors": list(nuisance),
            "comparisons": comparisons}


def t2_rows(levels=LV2, r=4, w=2, s=3, *, reps=None, unit_dev=None, wafer_label=None,
            site_label=None, site_dev=None, extra=None, two_level=False):
    """Complete T2 data. reps: per-level unit counts (default r for every level).
    unit_dev(level_index, rep) -> deviation; extra(level, rep, k, j, l) -> dict of
    extra columns. Runs are numbered R01.. in level order (k is the 1-based unit number)."""
    reps = reps or [r] * len(levels)
    wdev = centered(w, Q(1, 4))
    sdev = site_dev or centered(s, Q(1, 10))
    rows, k = [], 0
    for i, level in enumerate(levels):
        pattern = centered(reps[i], Q(1))
        for rep in range(reps[i]):
            k += 1
            u = unit_dev(i, rep) if unit_dev else pattern[rep]
            for j in range(1 if two_level else w):
                for l in range(len(sdev)):
                    y = Q(100) + EFFECT[level] + u + (Q(0) if two_level else wdev[j]) + sdev[l]
                    row = {"temp": level, "y": y,
                           "site": site_label(k, j, l) if site_label else str(l + 1)}
                    if two_level:
                        row["wafer"] = "W%02d" % k
                    else:
                        row["run"] = "R%02d" % k
                        row["wafer"] = wafer_label(k, j) if wafer_label else str(j + 1)
                    if extra:
                        row.update(extra(level, rep, k, j, l))
                    rows.append(row)
    return rows


T2_COLS = ["run", "wafer", "site", "temp", "y"]
T2_COLS_2L = ["wafer", "site", "temp", "y"]


_SHARED = ("levels", "r", "w", "s", "two_level")


def t2(fid, purpose, *, decl=None, rows=None, cols=None, **kw):
    dkw = {k: v for k, v in kw.items() if k in _SHARED}
    return Fixture(fid, purpose, decl or t2_decl(**dkw), cols or T2_COLS,
                   rows if rows is not None else t2_rows(**kw))


def drop(rows, pred):
    return [r for r in rows if not pred(r)]


def nuis(name, at, role="recorded", levels=None, crossed_with=None):
    f = {"name": name, "column": name, "recorded_at": at, "role": role}
    if levels is not None:
        f["levels"] = list(levels)
    if crossed_with is not None:
        f["crossed_with"] = crossed_with
    return f


# ---------------------------------------------------------------------------
# T1: lot > wafer > site, no treatment
# ---------------------------------------------------------------------------
def t1_decl(n=4, w=3, s=3, *, site=None):
    return {"stratum_declaration": 1, "claimed_template": "T1",
            "response": {"column": "y", "units": UNITS},
            "hierarchy": [{"name": "lot", "id_column": "lot", "count": n},
                          {"name": "wafer", "id_column": "wafer", "nested_in": "lot",
                           "count_per_parent": w},
                          dict({"name": "site", "id_column": "site", "nested_in": "wafer",
                                "count_per_parent": s}, **(site or {}))],
            "treatments": [], "nuisance_factors": [], "comparisons": []}


def t1_rows(n=4, w=3, s=3, *, sites=None):
    """sites: optional list of (label, deviation) used under every wafer."""
    ldev, wdev = centered(n, Q(1)), centered(w, Q(1, 4))
    sites = sites or [(str(l + 1), d) for l, d in enumerate(centered(s, Q(1, 10)))]
    rows = []
    for a in range(n):
        for j in range(w):
            for label, d in sites:
                rows.append({"lot": "L%d" % (a + 1), "wafer": str(j + 1), "site": label,
                             "y": Q(50) + ldev[a] + wdev[j] + d})
    return rows


T1_COLS = ["lot", "wafer", "site", "y"]


def t1(fid, purpose, *, decl=None, rows=None, **kw):
    return Fixture(fid, purpose, decl or t1_decl(**{k: v for k, v in kw.items() if k != "sites"}),
                   T1_COLS, rows if rows is not None else t1_rows(**kw))


# ---------------------------------------------------------------------------
# T3: whole plot = wafer (etch applied), subplot = position
# ---------------------------------------------------------------------------
A_EFF = [Q(0), Q(1, 2), Q(1), Q(3, 2)]
B_EFF = [Q(0), Q(1, 5), Q(2, 5), Q(3, 5)]
# Subplot deviations e[rep][position] per A level; rows and columns sum to zero.
E_BASE = {0: [Q(1, 4), Q(-1, 4), 0, 0], 1: [Q(-1, 4), Q(1, 4), 0, 0]}


def t3_decl(a=4, r=3, positions=("1", "2", "3", "4"), *, b_column="position"):
    b_levels = list(positions)
    return {"stratum_declaration": 1, "claimed_template": "T3",
            "response": {"column": "y", "units": UNITS},
            "hierarchy": [{"name": "wafer", "id_column": "wafer", "count": a * r},
                          {"name": "position", "id_column": "position", "nested_in": "wafer",
                           "count_per_parent": len(b_levels)}],
            "treatments": [
                {"name": "etch", "column": "etch", "levels": [str(i + 1) for i in range(a)],
                 "applied_to": "wafer", "replicates_per_level": r, "assignment": dict(ASSIGN)},
                {"name": "pos", "column": b_column, "levels": b_levels,
                 "applied_to": "position", "replicates_per_level": a * r,
                 "assignment": {"method": "inherent",
                                "description": "Synthetic fixture: position on the wafer."}}],
            "nuisance_factors": [],
            "comparisons": [{"id": "etch_overall", "kind": "overall", "factors": ["etch"]},
                            {"id": "pos_overall", "kind": "overall", "factors": ["pos"]},
                            {"id": "etch_by_pos", "kind": "interaction",
                             "factors": ["etch", "pos"]}],
            "split_plot": {"whole_plot_factor": "etch", "subplot_factor": "pos"}}


def t3_rows(a=4, r=3, positions=("1", "2", "3", "4"), *, reps=None, e_zero_levels=(),
            spike=None, extra=None):
    """reps: per-A-level whole-plot counts. spike: (wafer label, position, delta)."""
    reps = reps or [r] * a
    rows, n = [], 0
    for i in range(a):
        g = centered(reps[i], Q(1, 2))
        for rep in range(reps[i]):
            n += 1
            wafer = "W%02d" % n
            for p in positions:
                k = int(p) - 1
                e = Q(0) if i in e_zero_levels else Q(E_BASE.get(rep, [0, 0, 0, 0])[k])
                if spike and spike[0] == wafer and spike[1] == p:
                    e += spike[2]
                row = {"wafer": wafer, "position": p, "etch": str(i + 1),
                       "y": Q(6) + A_EFF[i] + g[rep] + B_EFF[k] + e}
                if extra:
                    row.update(extra(i, rep, wafer, p))
                rows.append(row)
    return rows


T3_COLS = ["wafer", "position", "etch", "y"]


def t3(fid, purpose, *, decl=None, rows=None, cols=None, **kw):
    dkw = {k: v for k, v in kw.items() if k in ("a", "r", "positions")}
    return Fixture(fid, purpose, decl or t3_decl(**dkw), cols or T3_COLS,
                   rows if rows is not None else t3_rows(**kw))


