#!/usr/bin/env python3
"""Run the WP2 evidence checker on every preregistered SYNTHETIC fixture and compare.

The checker is called with each fixture's declaration and data only. The
preregistered expectation is read afterwards, purely to compare (D-050). A fixture
MATCHES when the decision and the exact set of finding codes agree (D-048).

Writes `comparison.md` beside this file (generated; do not edit) and prints it.
Exit status 0 only if every fixture matches and every reference dataset has no
refusal-severity finding.

Usage: .venv/bin/python fixtures/synthetic_wp2/run_fixtures.py
"""
import argparse
import importlib.util
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT))

from stratum.evidence import check_evidence  # noqa: E402

_spec = importlib.util.spec_from_file_location("wp2_validate", HERE / "validate_registry.py")
_val = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_val)


def run_all():
    registry = json.loads((HERE / "expectations.json").read_text(encoding="utf-8"))
    effective = _val.effective_expectations(registry)
    rows = []
    for f in registry["fixtures"]:
        res = check_evidence(HERE / f["files"]["declaration"], HERE / f["files"]["data"])
        version, exp_dec, exp_cat = effective[f["id"]]
        actual = (res.decision, tuple(res.categories))
        v1 = (f["expected_decision"], tuple(sorted(f["expected_categories"])))
        rows.append({"id": f["id"], "version": version, "expected_decision": exp_dec,
                     "actual_decision": res.decision, "expected_categories": list(exp_cat),
                     "actual_categories": list(res.categories),
                     "v1_decision": v1[0], "v1_categories": list(v1[1]),
                     "v1_match": actual == v1, "match": actual == (exp_dec, exp_cat)})
    refs = []
    for r in registry["reference_datasets"]:
        data = ROOT / r["data"]
        if not data.is_file():
            refs.append({"id": r["id"], "status": "SKIPPED (data not fetched; run "
                                                  "reference/fetch.py)", "ok": True})
            continue
        res = check_evidence(ROOT / r["declaration"], data)
        refused = [x.code for x in res.findings if x.severity == "refuse"]
        refs.append({"id": r["id"], "decision": res.decision, "categories": list(res.categories),
                     "ok": not refused,
                     "status": "MATCH (no refusal finding)" if not refused else
                               "MISMATCH: refusal %s" % refused})
    return rows, refs


def render(rows, refs):
    out = ["# WP2 fixture comparison (generated by run_fixtures.py; do not edit)", "",
           "SYNTHETIC fixtures. Expectations preregistered before the checker existed "
           "(D-050, D-051).", "",
           "\"v1\" is the frozen preregistration. \"Current\" applies documented post-freeze "
           "corrections (registry `corrections`); a fixture with a current version above 1 is a "
           "specification change, never counted as a preregistration match.", "",
           "| Fixture | Preregistered v1 | Current (v) | Actual | Expected codes (current) "
           "| Actual codes | v1 | Current |",
           "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        out.append("| %s | %s | %s (v%d) | %s | %s | %s | %s | %s |" % (
            r["id"], r["v1_decision"], r["expected_decision"], r["version"], r["actual_decision"],
            ", ".join(r["expected_categories"]) or "(none)",
            ", ".join(r["actual_categories"]) or "(none)",
            "MATCH" if r["v1_match"] else "**MISMATCH**",
            "MATCH" if r["match"] else "**MISMATCH**"))
    n_ok = sum(r["match"] for r in rows)
    n_v1 = sum(r["v1_match"] for r in rows)
    out += ["", "**Version-1 preregistration: %d of %d match the current checker.** "
                "Every version-1 mismatch must carry a documented correction." % (n_v1, len(rows)),
            "", "**Current expectations: %d of %d match; %d mismatch.**"
            % (n_ok, len(rows), len(rows) - n_ok),
            "", "## Reference datasets (published, not synthetic; structural outcome only)", "",
            "| Dataset | Decision | Codes | Result |", "|---|---|---|---|"]
    for r in refs:
        out.append("| %s | %s | %s | %s |" % (r["id"], r.get("decision", "-"),
                                             ", ".join(r.get("categories", [])) or "(none)",
                                             r["status"]))
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    rows, refs = run_all()
    text = render(rows, refs)
    target = HERE / "comparison.md"
    if args.check:
        if not target.exists() or target.read_text() != text:
            raise SystemExit("fixture comparison regeneration differs")
    else:
        target.write_text(text, encoding="utf-8")
    print(text, end="")
    registry = json.loads((HERE / "expectations.json").read_text(encoding="utf-8"))
    documented = {c["fixture_id"] for c in registry["corrections"]}
    undocumented = [r["id"] for r in rows if not r["v1_match"] and r["id"] not in documented]
    return 0 if (all(r["match"] for r in rows) and all(r["ok"] for r in refs)
                 and not undocumented) else 1


if __name__ == "__main__":
    sys.exit(main())
