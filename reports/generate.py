#!/usr/bin/env python3
"""WP4: regenerate the committed reports (DECISIONS.md D-076, D-077).

Each report directory holds `results.json` (stratum.results.build, reproducible mode) and
`report.md` (stratum.report.render of that results.json). Nothing here is hand-edited.

  reference/<dataset>/   the four published datasets (fetched by reference/fetch.py)
  synthetic_wp2/<id>/    WP2 SYNTHETIC fixtures chosen to exercise each reporting pathway;
                         they are not WP5 scenarios (no recorded expectation, no write-up)

Usage:
    .venv/bin/python reports/generate.py            # write every report and INDEX.md
    .venv/bin/python reports/generate.py --check    # verify they match the generator, and
                                                    # that each report.md renders from its
                                                    # results.json
"""
import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT))

from stratum.report import render  # noqa: E402
from stratum.results import build, dumps  # noqa: E402

DERIVED = ROOT / "reference" / "_fetched" / "derived"
DECL = ROOT / "declarations" / "examples"
FIXTURES = ROOT / "fixtures" / "synthetic_wp2"

PUBLISHED_LABEL = ("Published textbook / NIST-SEMATECH dataset, not synthetic and not fab "
                   "data: %s")
REFERENCE = [
    ("furnace", "t1_nist_furnace.yaml", "furnace.csv",
     "NIST/SEMATECH furnace case study (FURNACE.DAT), handbook 3.5.1"),
    ("oxide", "t1_memss_oxide.yaml", "oxide.csv",
     "MEMSS Oxide, the canonical T1 reproduction without Source (D-014)"),
    ("semiconductor", "t3_sasmixed_semiconductor.yaml", "semiconductor.csv",
     "SASmixed Semiconductor (Littell et al. 1996, Data Set 2.2(b)), split-plot"),
    ("lithography", "t1_nist_lithography.yaml", "lithography.csv",
     "NIST/SEMATECH lithography case study (LITHOGRA.DAT), optional reproduction only "
     "(D-015)"),
]
# One fixture per reporting pathway (D-076 item 7).
SYNTHETIC = [
    ("REP-01", "T2 analyzed; allocation available"),
    ("BLK-01", "blocked T2 analyzed; allocation with the balanced-crossing scenario"),
    ("ALIAS-03", "T2 with one wafer per run: WARN; allocation limited"),
    ("MISS-01", "missing-site exception: WARN; approximate test; allocation withheld"),
    ("DIAG-02", "diagnostic warnings (Brown-Forsythe, SD ratio)"),
    ("T3-01", "T3 analyzed, with the naive analysis beside it"),
    ("CONF-03", "complete confounding: refused; reassignment produced"),
    ("CONF-04", "complete confounding through nesting: reassignment over four chambers"),
    ("BLK-03", "declared block confounded and unbalanced: reassignment without precision"),
    ("CONF-08", "confounding below the experimental unit: no reassignment, reason given"),
    ("CONF-05", "partial confounding: refused, imbalance and precision loss reported"),
    ("REP-02", "one run per level in the data: refused; planning allocation (lower bounds)"),
    ("DECL-01", "one run per level declared: WP1 refusal; planning-only checks"),
    ("BAL-02", "unbalanced units: refused; outside the planning pathway"),
]


def targets():
    for name, decl, csv, caption in REFERENCE:
        yield ("reference/%s" % name, DECL / decl, DERIVED / csv, False,
               PUBLISHED_LABEL % caption, caption)
    reg = json.loads((FIXTURES / "expectations.json").read_text(encoding="utf-8"))
    files = {f["id"]: f["files"] for f in reg["fixtures"]}
    for fid, caption in SYNTHETIC:
        yield ("synthetic_wp2/%s" % fid, FIXTURES / files[fid]["declaration"],
               FIXTURES / files[fid]["data"], True, None, "SYNTHETIC: " + caption)


def generate():
    out, index = {}, []
    for rel, decl, data, synth, label, caption in targets():
        doc = build(decl, data, synthetic=synth, data_label=label, reproducible=True)
        text = dumps(doc)
        out[HERE / rel / "results.json"] = text
        out[HERE / rel / "report.md"] = render(json.loads(text))
        index.append("| [%s](%s/report.md) | %s | %s | %s | %s |" % (
            rel, rel, caption.replace("|", "\\|"), doc["decision"]["evidence_decision"],
            doc["allocation"]["status"], doc["reassignment"]["status"]))
    head = ["# Generated reports", "",
            "Generated by `reports/generate.py`. **Do not edit.** Each directory holds "
            "`results.json` and `report.md`, which is rendered from that results.json alone "
            "(D-076). The data are published textbook and NIST/SEMATECH datasets plus "
            "labelled SYNTHETIC fixtures; synthetic results show software behavior, not "
            "process realism.", "",
            "| Report | What it exercises | Decision | Allocation | Reassignment |",
            "|---|---|---|---|---|"]
    out[HERE / "INDEX.md"] = "\n".join(head + index) + "\n"
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    files = generate()
    bad = 0
    for path, text in files.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print("MISMATCH %s" % path.relative_to(ROOT))
                bad = 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    if args.check:
        for path in files:
            if path.name == "results.json" and path.exists():
                rep = path.with_name("report.md")
                doc = json.loads(path.read_text(encoding="utf-8"))
                if not rep.exists() or rep.read_text(encoding="utf-8") != render(doc):
                    print("MISMATCH %s does not render from its results.json"
                          % rep.relative_to(ROOT))
                    bad = 1
        print("reports match the generator" if not bad else "reports DIFFER from the generator")
    else:
        print("wrote %d files" % len(files))
    return bad


if __name__ == "__main__":
    sys.exit(main())
